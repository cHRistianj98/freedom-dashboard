function replaceInsensitive(value: string, source: string, target: string) {
  const escaped = source.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return value.replace(new RegExp(`\\b${escaped}\\b`, "giu"), (match) => {
    if (match === match.toUpperCase()) return target.toUpperCase();
    if (match[0] === match[0]?.toUpperCase()) return target.charAt(0).toUpperCase() + target.slice(1);
    return target;
  });
}

function englishToGerman(value: string) {
  let result = value;
  const phrases = [...germanPhraseMap.entries()].sort((a, b) => b[0].length - a[0].length);
  for (const [source, target] of phrases) {
    if (result.includes(source)) result = result.split(source).join(target);
  }
  for (const pair of fallbackWordPairs) result = replaceInsensitive(result, pair.en, pair.de);
  return result;
}

